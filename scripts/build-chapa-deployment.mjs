import { build } from 'esbuild';
import { mkdir, copyFile, readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const output=resolve('deployment/chapa-payment-fix');
await mkdir(resolve(output,'sql'),{recursive:true});
await mkdir(resolve(output,'setup'),{recursive:true});
for(const name of ['chapa-reconcile','chapa-initialize','chapa-verify','chapa-webhook','chapa-transfer']) {
  await build({entryPoints:[`supabase/functions/${name}/index.ts`],outfile:resolve(output,`${name}.ts`),
    bundle:true,format:'esm',platform:'neutral',target:'es2022',external:['https://*'],
    banner:{js:`// Supabase Dashboard function: ${name}\n// Generated by npm run build:chapa-deployment. Copy this entire file into index.ts.\n// No local _shared imports are required. Never paste payment secrets into this file.`},
  });
}
const migrations=(await readdir('supabase/migrations')).filter(name=>/^2026110[2456].*\.sql$/.test(name)).sort();
for(const name of migrations) await copyFile(resolve('supabase/migrations',name),resolve(output,'sql',name));
for(const [source,destination] of [['wallet-audit-deployment.md','DEPLOY.md'],['chapa-payment-lifecycle.md','PAYMENT-LIFECYCLE.md']]) {
  const guide=await readFile(resolve('docs',source),'utf8');
  await writeFile(resolve(output,destination),guide.replaceAll('wallet-audit-deployment.md','DEPLOY.md').replaceAll('chapa-payment-lifecycle.md','PAYMENT-LIFECYCLE.md'));
}
for(const name of ['chapa-reconciliation.sql','wallet-audit-operations.sql']) await copyFile(resolve('supabase/setup',name),resolve(output,'setup',name));
process.stdout.write(`Ready-to-paste functions and SQL files: ${output}\n`);
