import { build } from 'esbuild';
import { mkdir, copyFile, writeFile, readdir } from 'node:fs/promises';
import { resolve } from 'node:path';

const output=resolve('deployment/chapa-payment-fix');
await mkdir(resolve(output,'sql'),{recursive:true});
for(const name of ['chapa-reconcile','chapa-initialize','chapa-verify','chapa-webhook']) {
  await build({entryPoints:[`supabase/functions/${name}/index.ts`],outfile:resolve(output,`${name}.ts`),
    bundle:true,format:'esm',platform:'neutral',target:'es2022',external:['https://*'],
    banner:{js:`// Supabase Dashboard function: ${name}\n// Generated by npm run build:chapa-deployment. Copy this entire file into index.ts.\n// No local _shared imports are required. Never paste payment secrets into this file.`},
  });
}
const migrations=(await readdir('supabase/migrations')).filter(name=>/^2026110[24].*\.sql$/.test(name)).sort();
for(const name of migrations) await copyFile(resolve('supabase/migrations',name),resolve(output,'sql',name));
await writeFile(resolve(output,'DEPLOY.md'),`# Manual Supabase deployment

Project: zewcewkqruxlniavsrgj
App origin: https://serkle-app-five.vercel.app

1. In Supabase Dashboard, open Edge Functions and create a function named exactly
   chapa-reconcile. Use the editor, replace index.ts with the entire contents of
   chapa-reconcile.ts from this folder, and deploy it.
2. Turn OFF the legacy JWT verification toggle for chapa-reconcile. Its handler
   verifies the user's JWT through Supabase Auth or a scheduler secret itself.
   OPTIONS needs neither a JWT nor payment secrets and returns HTTP 204.
3. For working payments, also update chapa-initialize and chapa-verify using their
   matching files. Keep legacy JWT verification ON for those two functions.
   Create chapa-webhook using its file with legacy JWT verification OFF; it
   requires a valid Chapa signature on POST.
4. Edge secrets (Dashboard > Edge Functions > Secrets):
   CHAPA_SECRET_KEY = your existing Chapa server key (keep it private)
   CHAPA_MODE = live for a live key, test for a test key
   PAYMENT_RETURN_ORIGINS = https://serkle-app-five.vercel.app
   CHAPA_WEBHOOK_SECRET = the secret registered for the Chapa webhook
   CHAPA_RECONCILE_SECRET = a separate random secret for the scheduled job
5. Review database migration history before applying SQL. This folder includes
   the matching November migrations in chronological order. Apply only files not
   already applied, once, after earlier project migrations. Do not blindly rerun
   table-creation migrations. The payment functions require the schema in
   20261104140000_verified_chapa_payments.sql and its earlier dependencies.
6. See docs/chapa-payment-lifecycle.md in the repository for webhook registration,
   the reconciliation scheduler, and the approved payment/access rules.

If POST returns a configuration or missing-schema error after deployment, the
preflight is fixed but the remaining setup above is still required. No funds are
granted from a browser success message or from a preflight request.
`, 'utf8');
process.stdout.write(`Ready-to-paste functions and SQL files: ${output}\n`);
